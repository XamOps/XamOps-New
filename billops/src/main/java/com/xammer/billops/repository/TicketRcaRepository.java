package com.xammer.billops.repository;

import com.xammer.billops.domain.TicketRca;
import org.springframework.data.jpa.repository.JpaRepository;
import org.springframework.data.jpa.repository.Modifying;
import org.springframework.data.jpa.repository.Query;
import org.springframework.data.repository.query.Param;
import org.springframework.stereotype.Repository;
import org.springframework.transaction.annotation.Transactional;

@Repository
public interface TicketRcaRepository extends JpaRepository<TicketRca, Long> {
    // Basic CRUD operations are provided automatically.
    // You can add custom finders here later if needed (e.g., findByTicketId).

    /**
     * Deletes every RCA generated by the given user. ticket_rca.generated_by_user_id is a
     * NOT NULL foreign key, so these rows must be removed before the app_user row can be deleted.
     */
    @Modifying
    @Transactional
    @Query("DELETE FROM TicketRca r WHERE r.generatedBy.id = :userId")
    void deleteByGeneratedByUserId(@Param("userId") Long userId);
}