"""Generator for the GCP and Azure halves of the WAR control catalog.

Both advisories share the AWS workbook's column layout, so one generator serves both.
Attack-path and automation mappings live in war_paths_<provider>.py.

    python3 scripts/gen_war_catalog_provider.py gcp   "<path-to-GCP-advisory.xlsx>"
    python3 scripts/gen_war_catalog_provider.py azure "<path-to-Azure-advisory.xlsx>"
"""
import importlib
import sys
import zipfile
import xml.etree.ElementTree as ET

NS = '{http://schemas.openxmlformats.org/spreadsheetml/2006/main}'

PROVIDERS = {
    'gcp': {
        'id_prefix': 'GCP',
        'field': 'GCP',
        'class': 'GcpWarControlCatalog',
        'scope': 'project',
        'manual_note': ('an API XamOps does not hold (Cloud Identity, Access Context '
                        'Manager, Workspace admin)'),
    },
    'azure': {
        'id_prefix': 'AZURE',
        'field': 'AZURE',
        'class': 'AzureWarControlCatalog',
        'scope': 'subscription',
        'manual_note': ('a tenant-scoped Microsoft Graph API XamOps does not hold '
                        '(Conditional Access, Entra app registrations, M365 Copilot)'),
    },
}

OUT_TEMPLATE = ('xamops-service/src/main/java/com/xammer/cloud/service/war/%s.java')


def read_rows(path):
    with zipfile.ZipFile(path) as z:
        shared = [''.join(x.text or '' for x in si.iter(NS + 't'))
                  for si in ET.fromstring(z.read('xl/sharedStrings.xml')).findall(NS + 'si')]
        sheet = ET.fromstring(z.read('xl/worksheets/sheet1.xml'))

    rows = []
    for row in sheet.iter(NS + 'row'):
        vals = []
        for c in row.findall(NS + 'c'):
            v = c.find(NS + 'v')
            inline = c.find(NS + 'is')
            if c.get('t') == 's' and v is not None:
                vals.append(shared[int(v.text)])
            elif inline is not None:
                vals.append(''.join(x.text or '' for x in inline.iter(NS + 't')))
            elif v is not None:
                vals.append(v.text)
            else:
                vals.append('')
        rows.append([x.strip() for x in vals])
    return rows


def parse(rows, superseded):
    header, out = None, []
    for r in rows:
        if r and r[0] == '#':
            header = r
            continue
        if header is None or not r or not r[0]:
            continue
        try:
            num = int(float(r[0]))
        except ValueError:
            continue
        if num in superseded:
            continue
        d = dict(zip(header, r))
        out.append({
            'num': num,
            'category': d.get('Category', ''),
            'sub': d.get('Sub-Category', ''),
            'title': d.get('Best Practice / Control', ''),
            'desc': d.get('Description & Implementation Steps', ''),
            'sev': d.get('Severity', ''),
            'tools': d.get('Tools / Services', ''),
            'ref': d.get('References', ''),
            'ctype': d.get('Category Type', ''),
            'impact': d.get('Business Impact if Not Implemented', ''),
            'ilevel': d.get('Impact Level', ''),
        })
    return out


def javadoc(paragraphs, width=84):
    """Wrap text into javadoc continuation lines, each prefixed with " * "."""
    out = []
    for para in paragraphs:
        out.append(' *')
        out.append(' * <p>')
        line = ''
        for word in para.split(' '):
            if line and len(line) + len(word) + 1 > width:
                out.append(' * ' + line)
                line = word
            else:
                line = (line + ' ' + word) if line else word
        if line:
            out.append(' * ' + line)
    return '\n' + '\n'.join(out)


def jstr(s):
    """Emit a Java string literal, wrapped so no source line runs long."""
    s = (s or '').replace('\\', '\\\\').replace('"', '\\"')
    s = ' '.join(s.split())
    if len(s) <= 88:
        return '"%s"' % s
    lines, cur = [], ''
    for w in s.split(' '):
        # `cur and` guards against an empty leading literal when a single token
        # (a long documentation URL) already exceeds the wrap width.
        if cur and len(cur) + len(w) + 1 > 88:
            lines.append(cur)
            cur = w
        else:
            cur = (cur + ' ' + w) if cur else w
    if cur:
        lines.append(cur)
    parts = ['"%s%s"' % (ln, ' ' if i < len(lines) - 1 else '')
             for i, ln in enumerate(lines)]
    return ('\n' + ' ' * 28 + '+ ').join(parts)


HEADER = '''package com.xammer.cloud.service.war;

import com.xammer.cloud.dto.war.WarAttackPath;
import com.xammer.cloud.dto.war.WarControl;

import java.util.List;
import java.util.Map;
import java.util.stream.Collectors;

/**
 * The %(pretty)s hardening baseline WAR evaluates a %(scope)s against.
 *
 * <p>
 * GENERATED by scripts/gen_war_catalog_provider.py from the %(pretty)s Cloud Security
 * Advisory workbook. Do not hand-edit; regenerate instead.
 *
 * <p>
 * %(count)d controls. Ids stay aligned to the workbook's own numbering so any control
 * can be traced back to its row.%(dedup)s%(automated_note)s
 */
public final class %(cls)s {

    private %(cls)s() {
    }

    public static final List<WarControl> %(field)s = List.of('''

FOOTER = ''');

    /** Indexed by control id for O(1) lookup when merging check results. */
    public static final Map<String, WarControl> %(field)s_BY_ID = %(field)s.stream()
            .collect(Collectors.toUnmodifiableMap(c -> c.id(), c -> c));

    /** Category display order, matching the source advisory. */
    public static final List<String> %(field)s_CATEGORY_ORDER = %(field)s.stream()
            .map(c -> c.category())
            .distinct()
            .toList();
}
'''


def main():
    if len(sys.argv) < 3:
        raise SystemExit(__doc__)
    provider = sys.argv[1].lower()
    if provider not in PROVIDERS:
        raise SystemExit('Unknown provider %r; expected one of %s'
                         % (provider, sorted(PROVIDERS)))
    cfg = PROVIDERS[provider]
    src = sys.argv[2]

    mapping = importlib.import_module('war_paths_%s' % provider)
    controls = parse(read_rows(src), mapping.SUPERSEDED)

    missing = [c['num'] for c in controls if c['num'] not in mapping.PATHS]
    if missing:
        raise SystemExit('No attack-path mapping for controls: %s' % missing)

    items = []
    for c in controls:
        n = c['num']
        paths = ', '.join('WarAttackPath.%s' % p for p in mapping.PATHS[n])
        items.append('''            new WarControl("%s-%d", %d,
                    %s,
                    %s,
                    %s,
                    %s,
                    %s,
                    %s,
                    %s,
                    %s,
                    %s,
                    %s,
                    List.of(%s), %s)''' % (
            cfg['id_prefix'], n, n,
            jstr(c['category']), jstr(c['sub']), jstr(c['title']), jstr(c['desc']),
            jstr(c['sev']), jstr(c['tools']), jstr(c['ref']), jstr(c['ctype']),
            jstr(c['impact']), jstr(c['ilevel']),
            paths, 'true' if n in mapping.AUTOMATED else 'false'))

    dedup_note = ''
    if mapping.SUPERSEDED:
        span = '%d-%d' % (min(mapping.SUPERSEDED), max(mapping.SUPERSEDED))
        dedup_note = javadoc([
            'The workbook numbers more rows than there are distinct controls: its AI '
            'section was drafted twice, and rows %s are an earlier pass superseded by '
            'later entries sharing the same reference URLs. Those are dropped here — '
            'keeping both would double-count AI controls in the score and inflate the '
            'AI Token Abuse attack path.' % span])

    fields = {
        'pretty': 'Azure' if provider == 'azure' else 'GCP',
        'scope': cfg['scope'],
        'count': len(controls),
        'cls': cfg['class'],
        'field': cfg['field'],
        'service': cfg['class'].replace('WarControlCatalog', 'WarService'),
        'manual_note': cfg['manual_note'],
        'automated_note': javadoc([
            '{@code automated == true} means {@code %s} evaluates the control against '
            'live %s state. The rest need %s or a human judgement call, and surface as '
            'MANUAL rather than a false pass.'
            % (cfg['class'].replace('WarControlCatalog', 'WarService'),
               cfg['scope'], cfg['manual_note'])]),
        'dedup': dedup_note,
    }

    out_path = OUT_TEMPLATE % cfg['class']
    with open(out_path, 'w') as fh:
        fh.write((HEADER % fields) + '\n' + ',\n\n'.join(items) + (FOOTER % fields))

    automated = len([c for c in controls if c['num'] in mapping.AUTOMATED])
    print('wrote %d controls to %s' % (len(items), out_path))
    if mapping.SUPERSEDED:
        print('  dropped %d superseded rows: %s'
              % (len(mapping.SUPERSEDED), sorted(mapping.SUPERSEDED)))
    print('  automated=%d manual=%d' % (automated, len(controls) - automated))


if __name__ == '__main__':
    main()
