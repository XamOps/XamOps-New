"""Generator for the GCP half of WarControlCatalog, from the XamSecure GCP advisory.

Emits GcpWarControlCatalog.java. Run after any revision to the workbook:

    python3 scripts/gen_gcp_war_catalog.py "<path-to-GCP-advisory.xlsx>"
"""
import sys
import zipfile
import xml.etree.ElementTree as ET

from war_paths_gcp import AUTOMATED, PATHS, SUPERSEDED

NS = '{http://schemas.openxmlformats.org/spreadsheetml/2006/main}'
OUT = ('xamops-service/src/main/java/com/xammer/cloud/service/war/'
       'GcpWarControlCatalog.java')


def read_rows(path):
    with zipfile.ZipFile(path) as z:
        shared = [''.join(x.text or '' for x in si.iter(NS + 't'))
                  for si in ET.fromstring(z.read('xl/sharedStrings.xml')).findall(NS + 'si')]
        sheet = ET.fromstring(z.read('xl/worksheets/sheet1.xml'))

    rows = []
    for row in sheet.iter(NS + 'row'):
        vals = []
        for c in row.findall(NS + 'c'):
            v = c.find(NS + 'v')
            inline = c.find(NS + 'is')
            if c.get('t') == 's' and v is not None:
                vals.append(shared[int(v.text)])
            elif inline is not None:
                vals.append(''.join(x.text or '' for x in inline.iter(NS + 't')))
            elif v is not None:
                vals.append(v.text)
            else:
                vals.append('')
        rows.append([x.strip() for x in vals])
    return rows


def parse(rows):
    header, out = None, []
    for r in rows:
        if r and r[0] == '#':
            header = r
            continue
        if header is None or not r or not r[0]:
            continue
        try:
            num = int(float(r[0]))
        except ValueError:
            continue
        if num in SUPERSEDED:
            continue
        d = dict(zip(header, r))
        out.append({
            'num': num,
            'category': d.get('Category', ''),
            'sub': d.get('Sub-Category', ''),
            'title': d.get('Best Practice / Control', ''),
            'desc': d.get('Description & Implementation Steps', ''),
            'sev': d.get('Severity', ''),
            'tools': d.get('Tools / Services', ''),
            'ref': d.get('References', ''),
            'ctype': d.get('Category Type', ''),
            'impact': d.get('Business Impact if Not Implemented', ''),
            'ilevel': d.get('Impact Level', ''),
        })
    return out


def jstr(s):
    """Emit a Java string literal, wrapped so no source line runs long."""
    s = (s or '').replace('\\', '\\\\').replace('"', '\\"')
    s = ' '.join(s.split())
    if len(s) <= 88:
        return '"%s"' % s
    lines, cur = [], ''
    for w in s.split(' '):
        # `cur and` guards against an empty leading literal when a single token
        # (a long documentation URL) already exceeds the wrap width.
        if cur and len(cur) + len(w) + 1 > 88:
            lines.append(cur)
            cur = w
        else:
            cur = (cur + ' ' + w) if cur else w
    if cur:
        lines.append(cur)
    parts = ['"%s%s"' % (ln, ' ' if i < len(lines) - 1 else '')
             for i, ln in enumerate(lines)]
    return ('\n' + ' ' * 28 + '+ ').join(parts)


HEADER = '''package com.xammer.cloud.service.war;

import com.xammer.cloud.dto.war.WarAttackPath;
import com.xammer.cloud.dto.war.WarControl;

import java.util.List;
import java.util.Map;
import java.util.stream.Collectors;

/**
 * The GCP hardening baseline WAR evaluates a project against.
 *
 * <p>
 * GENERATED by scripts/gen_gcp_war_catalog.py from the XamSecure GCP Cloud Security
 * Advisory workbook. Do not hand-edit; regenerate instead.
 *
 * <p>
 * The workbook carries 96 numbered rows but only %(count)d distinct controls. Its AI
 * section was drafted twice: rows 63-71 are an earlier, shorter pass superseded by the
 * 72-88 block, sharing reference URLs and differing only in wording. Those nine are
 * dropped here — keeping both would double-count AI controls in the score and inflate
 * the AI Token Abuse attack path. Ids stay aligned to the workbook's own numbering so
 * any control can be traced back to its row.
 *
 * <p>
 * {@code automated == true} means {@code GcpWarService} evaluates the control against
 * live project state. The rest need an API XamOps does not hold (Cloud Identity,
 * Access Context Manager, Workspace admin) or a human judgement call, and surface as
 * MANUAL rather than a false pass.
 */
public final class GcpWarControlCatalog {

    private GcpWarControlCatalog() {
    }

    public static final List<WarControl> GCP = List.of('''

FOOTER = ''');

    /** Indexed by control id for O(1) lookup when merging check results. */
    public static final Map<String, WarControl> GCP_BY_ID = GCP.stream()
            .collect(Collectors.toUnmodifiableMap(c -> c.id(), c -> c));

    /** Category display order, matching the source advisory. */
    public static final List<String> GCP_CATEGORY_ORDER = GCP.stream()
            .map(c -> c.category())
            .distinct()
            .toList();
}
'''


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else 'XamSecure Cloud Security Advisory_GCP.xlsx'
    controls = parse(read_rows(src))

    missing_paths = [c['num'] for c in controls if c['num'] not in PATHS]
    if missing_paths:
        raise SystemExit('No attack-path mapping for controls: %s' % missing_paths)

    items = []
    for c in controls:
        n = c['num']
        paths = ', '.join('WarAttackPath.%s' % p for p in PATHS[n])
        items.append('''            new WarControl("GCP-%d", %d,
                    %s,
                    %s,
                    %s,
                    %s,
                    %s,
                    %s,
                    %s,
                    %s,
                    %s,
                    %s,
                    List.of(%s), %s)''' % (
            n, n,
            jstr(c['category']), jstr(c['sub']), jstr(c['title']), jstr(c['desc']),
            jstr(c['sev']), jstr(c['tools']), jstr(c['ref']), jstr(c['ctype']),
            jstr(c['impact']), jstr(c['ilevel']),
            paths, 'true' if n in AUTOMATED else 'false'))

    with open(OUT, 'w') as fh:
        fh.write((HEADER % {'count': len(controls)}) + '\n'
                 + ',\n\n'.join(items) + FOOTER)

    automated = len([c for c in controls if c['num'] in AUTOMATED])
    print('wrote %d controls to %s' % (len(items), OUT))
    print('  dropped %d superseded rows: %s'
          % (len(SUPERSEDED), sorted(SUPERSEDED)))
    print('  automated=%d manual=%d' % (automated, len(controls) - automated))


if __name__ == '__main__':
    main()
