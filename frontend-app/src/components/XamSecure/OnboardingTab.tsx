import React, { useState } from 'react';
import { Icon } from '@iconify/react';
import { useUpwindOnboarding } from '../../hooks/useUpwindOnboarding';
import SensorDeployPanel from './SensorDeployPanel';
import type { OnboardingAccount } from '../../types/xamsecure';

interface Props {
  accounts: OnboardingAccount[] | null;
  isLoading: boolean;
  /** Re-reads the account list after a status change, so the badge is not left stale. */
  onRefresh?: () => void;
}

const STATUS_LABEL: Record<string, string> = {
  CONNECTED: 'Connected',
  PENDING: 'Waiting for first scan',
  NOT_CONNECTED: 'Not connected',
};

/**
 * Customer-facing onboarding.
 *
 * Connect opens Upwind's CloudFormation stack pre-filled. Nothing is asked of the customer
 * beyond confirming it: the Upwind credentials are Xammer's, injected server-side, and the
 * external ID is generated by the stack itself rather than entered anywhere.
 */
const OnboardingTab: React.FC<Props> = ({ accounts, isLoading, onRefresh }) => {
  const [copiedId, setCopiedId] = useState<string | null>(null);
  // Shared with Add Account → Security Monitoring. See useUpwindOnboarding for why the launch
  // URL is never held in state or in an href.
  const { busyId, checks, errors, disconnects, connect, check, disconnect } =
    useUpwindOnboarding(onRefresh);
  const [confirmId, setConfirmId] = useState<string | null>(null);
  const rows = accounts ?? [];

  const copy = async (acct: OnboardingAccount) => {
    if (!acct.sensorInstallCommand) return;
    await navigator.clipboard.writeText(acct.sensorInstallCommand);
    setCopiedId(acct.cloudAccountId);
    window.setTimeout(() => setCopiedId(null), 2000);
  };

  if (isLoading && rows.length === 0) {
    return <div className="text-center py-16 text-sm text-gray-400">Loading onboarding status...</div>;
  }

  return (
    <div className="space-y-4">
      {/* Once, above the accounts: the sensor script is org-wide, so it is not a per-account
          artifact. Only rendered when there is at least one account to monitor. */}
      {rows.length > 0 && <SensorDeployPanel />}
      {rows.map((a) => {
        const busy = busyId === a.cloudAccountId;
        const result = checks[a.cloudAccountId];
        const error = errors[a.cloudAccountId];
        const connected = a.status === 'CONNECTED';
        return (
          <div key={a.cloudAccountId} className="bg-white border border-gray-200 rounded-xl shadow-sm p-5">
            <div className="flex items-center justify-between gap-3">
              <div className="min-w-0">
                <p className="text-sm font-bold text-gray-900">{a.accountName}</p>
                <p className="text-[11px] text-gray-400 font-mono">{a.provider} · {a.cloudAccountId}</p>
              </div>
              <div className="flex items-center gap-2 flex-shrink-0">
                <span className={`px-3 py-1 rounded-full text-[10px] font-bold ${
                  connected ? 'bg-gray-900 text-white'
                  : a.status === 'PENDING' ? 'bg-gray-300 text-gray-800'
                  : 'bg-gray-100 text-gray-500'}`}>
                  {STATUS_LABEL[a.status] ?? a.status}
                </span>
                {a.selfServiceSupported && !connected && (
                  <>
                    <button type="button" onClick={() => connect(a)} disabled={busy}
                            className="px-3 py-1.5 rounded-md text-[11px] font-semibold bg-[rgba(0,0,0,0.88)] text-white hover:bg-black disabled:opacity-50 transition-colors">
                      {a.status === 'PENDING' ? 'Re-open stack' : 'Connect account'}
                    </button>
                    {/* Offered for NOT_CONNECTED too: an account connected outside XamOps starts
                        there, and without this it had no button that could re-check it. */}
                    <button type="button" onClick={() => check(a)} disabled={busy}
                            className="px-3 py-1.5 rounded-md text-[11px] font-semibold border border-gray-200 hover:bg-gray-50 disabled:opacity-50 transition-colors">
                      {busy ? 'Checking…' : 'Check connection'}
                    </button>
                  </>
                )}
                {a.selfServiceSupported && (connected || a.status === 'PENDING') && (
                  <button type="button" onClick={() => setConfirmId(a.cloudAccountId)}
                          disabled={busy}
                          className="px-3 py-1.5 rounded-md text-[11px] font-semibold border border-gray-200 text-gray-600 hover:bg-gray-50 disabled:opacity-50 transition-colors">
                    Disconnect
                  </button>
                )}
              </div>
            </div>

            {/* Inline, next to the account, because the second step is the one people skip:
                deregistering here does not remove the IAM role or the stored credential from
                their AWS account — only deleting the stack does. */}
            {confirmId === a.cloudAccountId && (
              <div className="mt-3 rounded-lg border border-gray-200 bg-gray-50 p-3">
                <p className="text-xs font-semibold text-gray-800">
                  Stop security monitoring for {a.accountName}?
                </p>
                <p className="mt-1 text-xs text-gray-600">
                  New findings stop immediately. Existing findings are kept for your records.
                  Afterwards, delete the CloudFormation stack
                  {a.stackName && <> <span className="font-mono">{a.stackName}</span></>}
                  {a.stackRegion && <> in <span className="font-mono">{a.stackRegion}</span></>}
                  {' '}to remove the IAM role and stored credential from your AWS account.
                </p>
                <div className="mt-2.5 flex items-center gap-2">
                  <button type="button" disabled={busy}
                          onClick={async () => { await disconnect(a); setConfirmId(null); }}
                          className="px-3 py-1.5 rounded-md text-[11px] font-semibold bg-red-600 text-white hover:bg-red-700 disabled:opacity-50 transition-colors">
                    {busy ? 'Disconnecting…' : 'Disconnect'}
                  </button>
                  <button type="button" onClick={() => setConfirmId(null)}
                          className="px-3 py-1.5 rounded-md text-[11px] font-semibold border border-gray-200 hover:bg-white transition-colors">
                    Cancel
                  </button>
                </div>
              </div>
            )}

            {disconnects[a.cloudAccountId] && (
              <p className="mt-3 text-xs text-gray-600">{disconnects[a.cloudAccountId].message}</p>
            )}

            {/* Not connected, self-service available: say what the button will do. Opening a
                CloudFormation console in a new tab is a surprising thing to do unannounced. */}
            {!connected && a.selfServiceSupported && a.status !== 'PENDING' && (
              <p className="mt-3 text-xs text-gray-500">
                Connect opens AWS CloudFormation in a new tab with everything filled in. Review
                and create the stack in account {a.cloudAccountId}; findings appear here once the
                first scan completes.
              </p>
            )}

            {a.status === 'PENDING' && (
              <div className="mt-3 text-xs text-gray-500 space-y-1">
                <p>
                  Stack <span className="font-mono text-gray-700">{a.stackName}</span>
                  {a.stackRegion && <> in <span className="font-mono text-gray-700">{a.stackRegion}</span></>}.
                  This page updates itself once Upwind reports the first assets.
                </p>
                {a.stackRequestedAt && (
                  <p className="text-[11px] text-gray-400">
                    Started {new Date(a.stackRequestedAt).toLocaleString()}
                  </p>
                )}
              </div>
            )}

            {connected && a.connectionVerifiedAt && (
              <p className="mt-3 text-xs text-gray-500">
                Verified {new Date(a.connectionVerifiedAt).toLocaleString()} — Upwind is reporting
                assets for this account.
              </p>
            )}

            {!connected && !a.onboardingAllowed && (
              <p className="mt-3 text-xs text-gray-500">
                Security monitoring is not enabled for your organization. Contact your XamOps
                administrator to have it turned on.
              </p>
            )}
            {!a.selfServiceSupported && a.onboardingAllowed && !connected && (
              <p className="mt-3 text-xs text-gray-500">
                Self-service connection covers AWS today. For {a.provider}, contact your XamOps
                administrator to enable XamSecure coverage.
              </p>
            )}

            {result && (
              <p className={`mt-3 text-xs ${result.reportingAssets ? 'text-emerald-700' : 'text-gray-500'}`}>
                {result.message}
              </p>
            )}
            {error && (
              <p className="mt-3 text-xs text-red-600" role="alert">{error}</p>
            )}

            {a.sensorInstallCommand && (
              <div className="mt-4">
                <p className="text-[10px] font-semibold text-gray-500 uppercase tracking-wide mb-1.5">
                  Sensor install command for this account
                </p>
                <div className="flex items-start gap-2">
                  <pre className="flex-1 bg-gray-50 border border-gray-200 rounded-lg p-3 text-[11px] text-gray-700 overflow-x-auto">
                    {a.sensorInstallCommand}
                  </pre>
                  <button onClick={() => copy(a)}
                          className="p-2 border border-gray-200 rounded-lg hover:bg-gray-50"
                          aria-label="Copy install command">
                    <Icon icon={copiedId === a.cloudAccountId ? 'mdi:check' : 'mdi:content-copy'} width={14} />
                  </button>
                </div>
              </div>
            )}
          </div>
        );
      })}
      {rows.length === 0 && !isLoading && (
        <div className="text-center py-16 bg-white border border-gray-200 rounded-xl shadow-sm text-sm text-gray-400">
          No cloud accounts found. Add a cloud account to XamOps first.
        </div>
      )}
    </div>
  );
};

export default OnboardingTab;
