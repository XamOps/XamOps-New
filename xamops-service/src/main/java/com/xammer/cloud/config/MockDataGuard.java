package com.xammer.cloud.config;

import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.boot.context.event.ApplicationReadyEvent;
import org.springframework.context.event.EventListener;
import org.springframework.core.env.Environment;
import org.springframework.stereotype.Component;

import java.util.Arrays;
import java.util.List;

/**
 * Refuses to start a production-like profile with cost mock data enabled.
 *
 * <p>{@code aws.costexplorer.mock=true} makes {@code PricingService},
 * {@code ReservationService} and {@code AwsPricingService} return values generated by
 * {@code CostMockService} — seeded pseudo-random numbers, not real cloud data. It exists so
 * local development does not incur Cost Explorer charges.
 *
 * <p>The risk is that the flag is invisible once set: every figure on the dashboard would be
 * fiction while looking entirely plausible, and a customer could make purchasing decisions
 * against invented numbers. This guard fails startup rather than allowing that, and logs a
 * prominent banner whenever mock mode is active in any profile.
 */
@Component
public class MockDataGuard {

    private static final Logger logger = LoggerFactory.getLogger(MockDataGuard.class);

    /** Profiles where mock cost data must never be served. */
    private static final List<String> PRODUCTION_LIKE_PROFILES =
            List.of("prod", "production", "uat", "preprod", "sit");

    private final Environment environment;
    private final boolean useMockData;

    public MockDataGuard(Environment environment,
                         @Value("${aws.costexplorer.mock:false}") boolean useMockData) {
        this.environment = environment;
        this.useMockData = useMockData;
    }

    @EventListener(ApplicationReadyEvent.class)
    void verifyMockDataIsSafe() {
        if (!useMockData) {
            return;
        }

        String[] activeProfiles = environment.getActiveProfiles();
        String offending = Arrays.stream(activeProfiles)
                .filter(p -> PRODUCTION_LIKE_PROFILES.contains(p.toLowerCase()))
                .findFirst()
                .orElse(null);

        if (offending != null) {
            throw new IllegalStateException(String.format(
                    "aws.costexplorer.mock=true is set while the '%s' profile is active. Mock mode "
                            + "serves generated cost, pricing and reservation figures instead of real cloud "
                            + "data, so every number shown would be fabricated. Set "
                            + "aws.costexplorer.mock=false for this environment.",
                    offending));
        }

        logger.warn("========================================================================");
        logger.warn(" MOCK COST DATA IS ENABLED (aws.costexplorer.mock=true)");
        logger.warn(" Pricing, cost and reservation figures are GENERATED, not real.");
        logger.warn(" Active profiles: {}", Arrays.toString(activeProfiles));
        logger.warn("========================================================================");
    }
}
